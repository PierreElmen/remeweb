        <h2>Screen Time (Family Controls)</h2>
        <p>Re:Me uses Apple’s <strong>Family Controls / Screen Time APIs</strong> to temporarily limit app access during your chosen session.</p>
        <ul>
          <li>You grant permission yourself in-app.</li>
          <li>The app never sees a list of your apps or usage details; Apple provides anonymous control tokens only.</li>
          <li>You can revoke permission anytime in <em>Settings › Screen Time › Apps with Screen Time Access</em>.</li>
        </ul>
      </article>

