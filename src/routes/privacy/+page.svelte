        <h2>Where your data is stored</h2>
        <ul>
          <li><strong>Local-only by default:</strong> Session info (e.g., duration, streaks, achievements) is stored <em>only on your device</em>.</li>
          <li><strong>Optional iCloud backup:</strong> If you enable it, your data is stored securely in <em>your own iCloud account</em>, managed by Apple. The developer cannot access your iCloud data.</li>
          <li>Delete the app to remove all local data from your device.</li>
        </ul>
